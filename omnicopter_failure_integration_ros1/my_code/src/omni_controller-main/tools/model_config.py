#!/usr/bin/env python3
"""Derive constant thrust allocation and aggregate rigid inertia from this SDF.
Run from any directory. Requires numpy and PyYAML. Output is deterministic.
"""
from pathlib import Path
import math
import xml.etree.ElementTree as ET
import numpy as np
import yaml

PACKAGE = Path(__file__).resolve().parents[1]
MODEL = PACKAGE.parent / 'AeRoSim/uav_simulator/models/omnicopter/model.sdf'

def rotation(rpy):
    r,p,y = rpy
    cr,sr,cp,sp,cy,sy=math.cos(r),math.sin(r),math.cos(p),math.sin(p),math.cos(y),math.sin(y)
    return np.array([[cy*cp,cy*sp*sr-sy*cr,cy*sp*cr+sy*sr],
                     [sy*cp,sy*sp*sr+cy*cr,sy*sp*cr-cy*sr],[-sp,cp*sr,cp*cr]])

def load_model():
    model=ET.parse(MODEL).find('model')
    bodies=[]
    for link in model.findall('link'):
        pose=np.fromstring(link.findtext('pose','0 0 0 0 0 0'),sep=' ')
        rot=rotation(pose[3:]); inertial=link.find('inertial')
        if inertial is None: continue
        ipose=np.fromstring(inertial.findtext('pose','0 0 0 0 0 0'),sep=' ')
        mass=float(inertial.findtext('mass')); ir=rot@rotation(ipose[3:])
        node=inertial.find('inertia')
        get=lambda key:float(node.findtext(key,'0'))
        inertia=np.array([[get('ixx'),get('ixy'),get('ixz')],
                          [get('ixy'),get('iyy'),get('iyz')],[get('ixz'),get('iyz'),get('izz')]])
        bodies.append((mass,pose[:3]+rot@ipose[:3],ir@inertia@ir.T))
    mass=sum(x[0] for x in bodies); com=sum(m*p for m,p,_ in bodies)/mass
    inertia=sum(j+m*(np.dot(p-com,p-com)*np.eye(3)-np.outer(p-com,p-com)) for m,p,j in bodies)
    plugin=model.find("plugin[@name='command_motors']")
    directions=[1 if int(s)>0 else -1 for s in plugin.findtext('turning_directions').split()]
    drag=float(plugin.findtext('drag_const')); columns=[]
    for i in range(8):
        link=model.find(f"link[@name='rotor_{i}']")
        pose=np.fromstring(link.findtext('pose'),sep=' ')
        d=rotation(pose[3:])@np.array([0.,0.,1.])
        columns.append(np.r_[d,np.cross(pose[:3]-com,d)-directions[i]*drag*d])
    A=np.array(columns).T
    assert np.linalg.matrix_rank(A)==6
    base=model.find("link[@name='base_link']")
    base_com=np.fromstring(base.find('inertial').findtext('pose'),sep=' ')[:3]
    return mass,com-base_com,inertia,A,float(plugin.findtext('thrust_const')),float(plugin.findtext('throttle'))

if __name__=='__main__':
    mass,offset,J,A,k,rpm=load_model()
    # Preserve the legacy 1900-us command ceiling, converted by its adapter.
    rpm_ceiling=min(rpm,max(0.,-0.0101*1900**2+61.8029*1900-52696))
    thrust_ceiling=k*(rpm_ceiling*0.10472)**2
    settings=dict(mass=mass,allocation=A.ravel().tolist(),inertia=J.ravel().tolist(),
        thrust_min=[0.]*8,thrust_max=[float(thrust_ceiling)]*8,position_kp=[15.,15.,18.],position_kd=[10.,10.,12.],
        position_ki=[6.,6.,8.],attitude_kp=[8.5]*3,attitude_kd=[6.5]*3,
        max_v=0.1,alpha=1.,beta=1e-5,gamma=0.,clip_reference=False,
        max_solve_seconds=0.002,max_evaluations=80,constraint_tolerance=1e-6,
        frequency=250.,position_error_limit=0.5,velocity_error_limit=1.,integral_limit=1.,state_timeout=0.1)
    (PACKAGE/'config/failure_aware.yaml').write_text('# Generated by tools/model_config.py; u is rotor thrust [N].\n'+yaml.safe_dump(settings,sort_keys=False))
    sim={'direct_thrust':True,'thrust_constant':k,'max_rpm':rpm,'com_offset':offset.tolist()}
    (PACKAGE/'config/failure_sim.yaml').write_text(yaml.safe_dump(sim,sort_keys=False))
    # C++ fixture shares the SDF-derived physical parameters, not solver outputs.
    def numbers(a): return ','.join(f'{v:.17g}' for v in np.array(a).ravel())
    (PACKAGE/'test/model_fixture.hpp').write_text('#pragma once\n#include "feasible_allocator.hpp"\nnamespace fixture {\n'
        'inline omni::A68 allocation(){ omni::A68 a; a << '+numbers(A)+'; return a;}\n'
        'inline Eigen::Matrix3d inertia(){ Eigen::Matrix3d j; j << '+numbers(J)+'; return j;}\n'
        f'constexpr double mass={mass:.17g};\nconstexpr double thrust_max={thrust_ceiling:.17g};\n}}\n')
    print('mass',mass,'COM offset',offset.tolist(),'allocation singular values',np.linalg.svd(A)[1].tolist())
